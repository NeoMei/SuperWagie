export type CreationMessageKey = keyof typeof messages;
type CreationLocale = 'en' | 'zh-CN';
export const creationLocale = (locale: string | undefined): CreationLocale => /^en(?:-|$)/i.test(locale ?? '') ? 'en' : 'zh-CN';

export const creationText = (locale: string | undefined, key: CreationMessageKey, params: { [name: string]: string | number } = {}): string => {
  const message = messages[key][creationLocale(locale) === 'en' ? 1 : 0];
  return message.replace(/\{(\w+)\}/g, (token, name: string) => String(params[name] ?? token));
};
