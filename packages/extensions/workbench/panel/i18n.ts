export type WorkbenchMessage = keyof typeof messages;
type WorkbenchLocale = 'en' | 'zh-CN';
let locale: WorkbenchLocale = 'zh-CN';

export const setWorkbenchLocale = (value: string): void => { locale = value.toLowerCase().startsWith('en') ? 'en' : 'zh-CN'; };
export const workbenchLocale = (): WorkbenchLocale => locale;

export const t = (key: WorkbenchMessage, values: { [name: string]: string | number } = {}): string =>
  messages[key][locale].replace(/\{(\w+)\}/g, (placeholder: string, name: string) => String(values[name] ?? placeholder));

export const weekdayLabels = (): string[] => Array.from({ length: 7 }, (_, index) =>
  new Date(2026, 5, 1 + index).toLocaleDateString(locale, { weekday: 'short' }));

export const categoryLabel = (category: string): string => {
  if (category === '文档') return t('category.doc');
  if (category === '视频') return t('category.video');
  if (category === '网页') return t('category.page');
  return category;
};

export const weatherLabel = (label: string): string => {
  const entry = Object.entries(messages).find(([key, value]) => key.startsWith('weather.') && value['zh-CN'] === label);
  return entry ? entry[1][locale] : label;
};
