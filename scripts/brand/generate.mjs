#!/usr/bin/env node
/**
 * Writes retained OpenChamber assets from scripts/brand/geometry.mjs.
 * SuperWagie web and Electron artwork is maintained separately.
 *
 * Usage:
 *   bun run scripts/brand/generate.mjs          write retained assets
 *   bun run scripts/brand/generate.mjs --check  fail if a retained text output is out of date
 *
 * Images are rendered with sharp; their bytes depend on the libvips build, so
 * only text outputs are checked.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  FLAT_LOGO,
  FLAT_TIER_LIT,
  FLAT_TIER_OPACITY,
  FLAT_TIER_REST,
  flatLogoInner,
  flatLogoSvg,
  glyphSvg,
  glyphSymbolSvg,
  noTileIconSvg,
} from './geometry.mjs';
import { composeOnSquare, solidSquare, svgToPng } from './raster.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const at = (...parts) => join(repoRoot, ...parts);

const VSCODE_ASSETS = at('packages/vscode/assets');
const ANDROID_RES = at('packages/mobile/android/app/src/main/res');
const MOBILE_ASSETS = at('packages/mobile/assets');

const BLACK = '#000000';
const TRANSPARENT = { r: 0, g: 0, b: 0, alpha: 0 };

// ---------------------------------------------------------------------------
// Text outputs: whole files, and marked regions inside hand-written files.

const FLAT_MARK_START = '<!-- brand:flat-logo:start -->';
const FLAT_MARK_END = '<!-- brand:flat-logo:end -->';

/** In-app logo paths for a page script to animate: each tier carries its resting and lit opacity. */
const flatLogoInlineMarkup = () => flatLogoInner({ color: 'currentColor', idPrefix: 'oc-logo-' })
  .replace(/<path data-tier="(\d)"/g, (match, i) => `${match} data-rest="${FLAT_TIER_REST[i]}" data-lit="${FLAT_TIER_LIT[i]}"`);

const INLINE_LOGO_FILES = [
  'packages/vscode/src/webviewHtml.ts',
  'packages/web/server/lib/opencode/static-routes-runtime.js',
];

const replaceMarked = (source, file, markup) => {
  const start = source.indexOf(FLAT_MARK_START);
  const end = source.indexOf(FLAT_MARK_END);
  if (start < 0 || end < start) throw new Error(`${file}: missing ${FLAT_MARK_START} ... ${FLAT_MARK_END}`);
  return source.slice(0, start + FLAT_MARK_START.length) + markup + source.slice(end);
};

const flatLogoArtModule = () => {
  const { leftShade, rightShade, roof, roofOpacity, tiers, shell, stroke, wallStrength, wallStops } = FLAT_LOGO;
  const gradient = ({ stops, ...line }) => ({
    ...line,
    stops: stops.map(([offset, opacity]) => [offset, Number((opacity * wallStrength).toFixed(3))]),
  });
  const art = {
    shell,
    stroke,
    roof,
    roofOpacity,
    tiers,
    tierOpacity: FLAT_TIER_OPACITY,
    tierRest: FLAT_TIER_REST,
    tierLit: FLAT_TIER_LIT,
    walls: [
      { path: leftShade, gradient: gradient(wallStops.left) },
      { path: rightShade, gradient: gradient(wallStops.right) },
    ],
  };
  return `// Generated by scripts/brand/generate.mjs from scripts/brand/geometry.mjs. Do not edit.
// The in-app logo on a "-50 -50 100 100" view box, drawn in one colour.

export const OPEN_CHAMBER_LOGO_ART = ${toTypeScript(art)} as const;
`;
};

// A literal in the repository's style: unquoted keys, single quotes, short
// arrays of numbers on one line.
const toTypeScript = (value, indent = '') => {
  const inner = `${indent}  `;
  if (typeof value === 'string') return `'${value}'`;
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) {
    if (value.every((item) => typeof item === 'number')) return `[${value.join(', ')}]`;
    if (value.every((item) => Array.isArray(item))) return `[${value.map((item) => toTypeScript(item)).join(', ')}]`;
    return `[\n${value.map((item) => `${inner}${toTypeScript(item, inner)},`).join('\n')}\n${indent}]`;
  }
  return `{\n${Object.entries(value).map(([key, item]) => `${inner}${key}: ${toTypeScript(item, inner)},`).join('\n')}\n${indent}}`;
};

// Android vector drawables have no opacity on a group, only per path.
const androidNotificationVector = () => {
  const glyph = glyphSvg({ color: '#FFFFFF' });
  const paths = [...glyph.matchAll(/<path d="([^"]+)"(?: fill="[^"]+" fill-opacity="([\d.]+)")?\/>/g)];
  const strokes = paths.filter(([, , opacity]) => opacity === undefined).map(([, d]) => d).join(' ');
  const rings = paths.filter(([, , opacity]) => opacity !== undefined);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/brand/generate.mjs. Notification small icon: the OpenChamber glyph.
     Android tints it in the status bar and notification, so only its alpha matters. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="32"
    android:viewportHeight="32">
    <path
        android:fillColor="#00000000"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="1.8"
        android:strokeLineJoin="round"
        android:strokeLineCap="round"
        android:pathData="${strokes}" />
${rings.map(([, d, opacity]) => `    <path
        android:fillColor="#FFFFFFFF"
        android:fillAlpha="${opacity}"
        android:pathData="${d}" />`).join('\n')}
</vector>
`;
};

const androidBackgroundColor = () => `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${BLACK}</color>
</resources>
`;

const textOutputs = () => {
  const files = new Map([
    [at('docs/references/badges/openchamber-logo-dark.svg'), flatLogoSvg({ color: '#f5f5f7', size: 100 })],
    [at('docs/references/badges/openchamber-logo-light.svg'), flatLogoSvg({ color: '#100f0f', size: 100 })],
    [join(VSCODE_ASSETS, 'icon.svg'), glyphSvg({ size: 24, color: 'currentColor' })],
    [join(VSCODE_ASSETS, 'icon-titlebar.svg'), glyphSvg({ size: 24, color: '#73C991' })],
    [join(VSCODE_ASSETS, 'icon-scm-titlebar.svg'), glyphSvg({ size: 24, color: '#C5C5C5' })],
    [join(ANDROID_RES, 'drawable/ic_stat_notify.xml'), androidNotificationVector()],
    [join(ANDROID_RES, 'values/ic_launcher_background.xml'), androidBackgroundColor()],
    [at('packages/ui/src/components/ui/openChamberLogoArt.ts'), flatLogoArtModule()],
  ]);
  for (const file of INLINE_LOGO_FILES) {
    const path = at(file);
    files.set(path, replaceMarked(readFileSync(path, 'utf8'), file, flatLogoInlineMarkup()));
  }
  return files;
};

// ---------------------------------------------------------------------------
// Image outputs.

const DENSITIES = { ldpi: 0.75, mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

const imageOutputs = async () => {
  const images = new Map();
  const put = (path, buffer) => images.set(path, buffer);

  const noTile = noTileIconSvg();
  const onBlack = (share) => noTileIconSvg({ background: BLACK, cubeShare: share });
  put(at('docs/references/badges/openchamber-logo-dark.png'), await svgToPng(flatLogoSvg({ color: '#f5f5f7' }), 512));

  // VS Code Marketplace and chat avatar.
  put(join(VSCODE_ASSETS, 'app-icon.png'), await svgToPng(noTile, 512));

  // Android launcher: the cube on black. The adaptive foreground is inset by
  // the launcher XML; the legacy and round icons are complete pictures.
  const foreground = noTileIconSvg({ cubeShare: 0.6 });
  const monochrome = glyphSvg({ color: '#FFFFFF' });
  for (const [density, scale] of Object.entries(DENSITIES)) {
    const dir = join(ANDROID_RES, `mipmap-${density}`);
    const launcher = Math.round(48 * scale);
    put(join(dir, 'ic_launcher_background.png'), await solidSquare(launcher, BLACK));
    put(join(dir, 'ic_launcher_foreground.png'), await svgToPng(foreground, launcher));
    put(join(dir, 'ic_launcher.png'), await composeOnSquare({ png: await svgToPng(foreground, launcher), size: launcher, background: BLACK, inset: Math.round(launcher / 24), round: Math.round(launcher / 12) }));
    put(join(dir, 'ic_launcher_round.png'), await composeOnSquare({ png: await svgToPng(foreground, launcher), size: launcher, background: BLACK, round: 'circle' }));
    if (density !== 'ldpi') {
      // Themed icon: the glyph on a 108 dp canvas, like the adaptive layers.
      const themed = Math.round(108 * scale);
      put(join(dir, 'ic_launcher_monochrome.png'), await composeOnSquare({
        png: await svgToPng(monochrome, themed),
        size: themed,
        background: TRANSPARENT,
        inset: Math.round(themed * 0.2),
      }));
    }
  }
  put(join(MOBILE_ASSETS, 'icon-only.png'), await svgToPng(onBlack(0.6), 1024));
  put(join(MOBILE_ASSETS, 'icon-foreground.png'), await svgToPng(foreground, 1024));
  put(join(MOBILE_ASSETS, 'icon-background.png'), await solidSquare(1024, BLACK));

  return images;
};

// ---------------------------------------------------------------------------

const writeFile = (path, data) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, data);
};

const check = () => {
  const stale = [...textOutputs()].filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text);
  if (stale.length) {
    console.error(`Out of date, run \`bun run scripts/brand/generate.mjs\`:\n${stale.map(([path]) => `  ${relative(repoRoot, path)}`).join('\n')}`);
    process.exit(1);
  }
  console.log('Brand assets are up to date.');
};

const generate = async () => {
  for (const [path, text] of textOutputs()) writeFile(path, text);
  for (const [path, buffer] of await imageOutputs()) writeFile(path, buffer);
  console.log('Wrote retained OpenChamber assets.');

  // The retained OpenChamber sprite glyph shares this geometry.
  execFileSync('bun', ['run', at('scripts/generate-icon-sprite.mjs')], { stdio: 'inherit' });
  writeControlCenterSymbol();
};

// The iOS Control Center symbol retains the OpenChamber drawing.
const SYMBOL_PATH = at('packages/mobile/ios/App/OpenChamberWidget/Assets.xcassets/OCLogoSymbol.symbolset/oclogo-symbol.svg');
const writeControlCenterSymbol = () => {
  try {
    execFileSync('swiftdraw', ['--help'], { stdio: 'ignore' });
  } catch (error) {
    // swiftdraw prints its usage with a failing status; only a missing binary matters.
    if (error.code === 'ENOENT') {
      console.log('swiftdraw not found (brew install swiftdraw): the Control Center symbol was left as it is.');
      return;
    }
  }
  const tmp = mkdtempSync(join(tmpdir(), 'openchamber-symbol-'));
  try {
    const source = join(tmp, 'glyph.svg');
    writeFileSync(source, glyphSymbolSvg());
    execFileSync('swiftdraw', [source, '--format', 'sfsymbol', '--insets', 'auto', '--output', SYMBOL_PATH], { stdio: 'inherit' });
    console.log('Wrote the Control Center symbol.');
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
};

export { imageOutputs, textOutputs };

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) check();
  else await generate();
}
